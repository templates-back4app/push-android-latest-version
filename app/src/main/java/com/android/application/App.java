package com.android.application;

import android.app.Application;
import android.util.Log;

import com.google.firebase.messaging.FirebaseMessaging;
import com.parse.Parse;
import com.parse.ParseInstallation;
import com.parse.fcm.ParseFCM;

public class App extends Application {

    private static final String TAG = "App";

    @Override
    public void onCreate() {
        super.onCreate();

        Parse.initialize(new Parse.Configuration.Builder(this)
                .applicationId(getString(R.string.back4app_app_id))
                .clientKey(getString(R.string.back4app_client_key))
                .server(getString(R.string.back4app_server_url))
                .build());

        // Creates/updates the _Installation row Back4App uses to target this device.
        // ParseFCM only writes deviceToken and pushType, so the sender id is recorded here. It is
        // read from the resource generated by the google-services plugin, so it always matches
        // google-services.json instead of being hardcoded.
        ParseInstallation installation = ParseInstallation.getCurrentInstallation();
        installation.put("GCMSenderId", getString(R.string.gcm_defaultSenderId));
        installation.saveInBackground(e -> {
            if (e != null) {
                Log.e(TAG, "Installation not saved: " + e.getMessage(), e);
                return;
            }
            Log.d(TAG, "Installation saved: " + installation.getObjectId());
            registerFcmToken();
        });
    }

    /**
     * Parse 4.4.0 relies on the legacy FCM token flow: the token is delivered to
     * ParseFirebaseMessagingService#onNewToken, which only fires when the token is created or
     * rotated. The token is therefore also fetched explicitly here so the installation stays
     * registered on every launch.
     *
     * <p>FirebaseMessaging#getToken() is deprecated in favour of FirebaseMessaging#register(), but
     * that API requires the {@code firebase_messaging_installation_id_enabled} opt-in and delivers
     * the token through {@code onRegistered}, which the Parse SDK does not implement yet.
     */
    @SuppressWarnings("deprecation")
    private void registerFcmToken() {
        FirebaseMessaging.getInstance().getToken().addOnCompleteListener(task -> {
            if (!task.isSuccessful() || task.getResult() == null) {
                Log.e(TAG, "Could not fetch the FCM token", task.getException());
                return;
            }
            ParseFCM.register(task.getResult());
            Log.d(TAG, "FCM token registered with Parse.");
        });
    }
}
